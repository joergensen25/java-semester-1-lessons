package opgave07;

public class Cirkel {
    public static void main(String[] args) {
        System.out.println("Arealet af en cirkel med radius på 6,5 er som følger:");
        System.out.println(2*6.5*Math.PI);
        System.out.println("Omkredsen af en cirkel med radius på 6,5 er som følger:");
        System.out.println(Math.pow(6.5,2)*Math.PI);
    }
}
